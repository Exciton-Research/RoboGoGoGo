"""Generate manuscript macros from the checked-in evidence, without new experiments."""

import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
evidence = json.loads((root / "evidence/report.json").read_text())
assert evidence["source_commit"] == "a886d2a9d3a27c87a9e90a21ecfbc3259657b943", (
    "A changed source revision requires reviewing the manuscript first"
)
assert (
    hashlib.sha256(
        (root / "evidence/working-range-engineering-11.json").read_bytes()
    ).hexdigest()
    == evidence["historical_audit_sha256"]
)
regressions = evidence["regressions"]
smoke = evidence["capture_smoke"]
values = {
    "RegressionCount": regressions["tests"],
    "RegressionFailures": regressions["failures"],
    "RegressionErrors": regressions["errors"],
    "RegressionSkipped": regressions["skipped"],
    "PracticalCount": evidence["practical_geometry"]["counts"]["samples"],
    "PythonVersion": evidence["python"],
    "JaxVersion": evidence["dependencies"]["jax"],
    "NumpyVersion": evidence["dependencies"]["numpy"],
    "SmokeDuration": f"{smoke['time_after_s'] - smoke['time_before_s']:.3f}",
}
assert not any(regressions[key] for key in ("failures", "errors", "skipped"))
assert evidence["practical_geometry"]["status"] == "sampled_clear"
assert (
    evidence["practical_geometry"]["counts"]["rigid_clear"] == values["PracticalCount"]
)
(root / "evidence/results.tex").write_text(
    "% Generated by scripts/generate_results.py from evidence/report.json.\n"
    + "".join(
        "\\newcommand{\\" + key + "}{" + str(value) + "}\n"
        for key, value in values.items()
    )
)
print(json.dumps(values))
