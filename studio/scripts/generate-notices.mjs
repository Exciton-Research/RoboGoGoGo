// Preserve upstream license text from the packages actually installed by npm ci.
// No network access. Keep this output versioned alongside the dependency lockfile.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createHash } from "node:crypto";

const studio = fileURLToPath(new URL("../", import.meta.url));
const destination = fileURLToPath(
  new URL("../../THIRD_PARTY_NOTICES.md", import.meta.url),
);
const lockText = await readFile(path.join(studio, "package-lock.json"), "utf8");
const lock = JSON.parse(lockText);
const manifest = JSON.parse(
  await readFile(path.join(studio, "package.json"), "utf8"),
);
const legalName = /^(?:licen[sc]e|notice|copying|copyright)(?:[._-].*)?$/i;
const packages = [
  ...new Set([
    ...Object.keys(manifest.dependencies),
    "scheduler",
    "styled-jsx",
    "@swc/helpers",
    "tslib",
  ]),
].sort();
const sections = [
  "# Third-party notices",
  "Generated by `npm run notices --prefix studio` from the installed packages and the committed npm lockfile. Do not edit the upstream license text by hand.",
  "Upstream wording is preserved. Line endings are normalized to LF and trailing spaces are removed for a clean source diff.",
  `Dependency lockfile SHA-256: \`${createHash("sha256").update(lockText).digest("hex")}\`. Any lockfile change requires regeneration and review.`,
  "The project's original work is Apache-2.0. The third-party components below retain their own licenses; this file does not relicense them.",
  "This inventory covers Studio's direct browser libraries, fonts, supporting JavaScript, and the license/notice files shipped in Next.js's vendored compiler/runtime tree. Some vendored modules are build-time or platform-specific and may not occur in a particular browser bundle. Their notices are retained conservatively. Native build tools and Python dependencies are not redistributed as part of the static UI; their installed distributions carry their own notices.",
];

async function notice(directory, relative, heading) {
  const body = await readFile(path.join(directory, relative), "utf8");
  if (!body.trim())
    throw new Error(`Empty upstream notice: ${heading}/${relative}`);
  const normalized = body
    .replace(/\r\n?/g, "\n")
    .replace(/[ \t]+$/gm, "")
    .trimEnd();
  sections.push(
    `### ${heading}/${relative}\n\n\`\`\`\`text\n${normalized}\n\`\`\`\``,
  );
}

for (const name of packages) {
  const key = `node_modules/${name}`;
  const directory = path.join(studio, key);
  const info = JSON.parse(
    await readFile(path.join(directory, "package.json"), "utf8"),
  );
  if (lock.packages[key]?.version !== info.version) {
    throw new Error(
      `Installed ${name} does not match the lockfile; run npm ci.`,
    );
  }
  const filenames = (await readdir(directory))
    .filter((name) => legalName.test(name))
    .sort();
  if (!filenames.length)
    throw new Error(`No upstream license found for ${name}`);
  sections.push(
    `## ${name} ${info.version}\n\nDeclared license: ${info.license}. Source: https://www.npmjs.com/package/${name}/v/${info.version}`,
  );
  for (const filename of filenames) await notice(directory, filename, name);
}

const nextDirectory = path.join(studio, "node_modules/next");
const compiledFiles = [];
async function walk(directory, prefix = "dist/compiled") {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = `${prefix}/${entry.name}`;
    if (entry.isDirectory())
      await walk(path.join(directory, entry.name), relative);
    else if (entry.isFile() && legalName.test(entry.name))
      compiledFiles.push(relative);
  }
}
await walk(path.join(nextDirectory, "dist/compiled"));
if (!compiledFiles.length)
  throw new Error("Next.js vendored notices were not found");
sections.push(
  "## Next.js vendored dependencies\n\nThe following upstream notices are included in the installed Next.js version identified above.",
);
for (const relative of compiledFiles.sort())
  await notice(nextDirectory, relative, "next");

const output = `${sections.join("\n\n")}\n`;
if (process.argv.includes("--check")) {
  let saved;
  try {
    saved = await readFile(destination, "utf8");
  } catch {
    /* Report the regeneration command below. */
  }
  if (saved !== output)
    throw new Error(
      "Third-party notices are missing or stale. Run npm run notices --prefix studio and commit the result.",
    );
  console.log("Third-party notices match the installed dependency lockfile.");
} else {
  await writeFile(destination, output);
  console.log("Updated THIRD_PARTY_NOTICES.md");
}
